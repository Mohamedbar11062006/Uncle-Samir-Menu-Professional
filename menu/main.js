function escapeHTML(value = '') {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function loadCart() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    if (!Array.isArray(saved)) return [];

    return saved
      .map((savedItem) => {
        const product = menu.find((item) => item.id === Number(savedItem.id));
        if (!product) return null;
        const quantity = Math.max(1, Math.min(99, Number(savedItem.quantity) || 1));
        return { id: product.id, quantity };
      })
      .filter(Boolean);
  } catch {
    return [];
  }
}

function saveCart() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state.cart));
}

function getProduct(id) {
  return menu.find((item) => item.id === Number(id));
}

function getVisibleMenu() {
  const query = state.query.trim().toLowerCase();

  return menu.filter((item) => {
    const categoryMatch = state.category === 'all' || item.category === state.category;
    const queryMatch = !query || `${item.name} ${item.description}`.toLowerCase().includes(query);
    return categoryMatch && queryMatch;
  });
}

function renderMenu() {
  const visibleItems = getVisibleMenu();

  menuContainer.innerHTML = visibleItems.map((item) => `
    <article class="menu-card">
      <div class="card-media">
        <img src="${escapeHTML(item.image)}" alt="${escapeHTML(item.name)}" loading="lazy" decoding="async">
        <span class="card-category">${escapeHTML(categoryLabels[item.category] || item.category)}</span>
      </div>
      <div class="card-body">
        <h3>${escapeHTML(item.name)}</h3>
        <p>${escapeHTML(item.description)}</p>
        <div class="card-bottom">
          <div class="price"><small>EGP</small><strong>${item.price}</strong></div>
          <button class="add-button" type="button" data-add="${item.id}" aria-label="Add ${escapeHTML(item.name)} to cart">
            Add <span aria-hidden="true">+</span>
          </button>
        </div>
      </div>
    </article>
  `).join('');

  const countLabel = `${visibleItems.length} item${visibleItems.length === 1 ? '' : 's'}`;
  resultCount.textContent = countLabel;
  emptyState.hidden = visibleItems.length !== 0;
  menuContainer.hidden = visibleItems.length === 0;
}

function cartSummary() {
  return state.cart.reduce((summary, line) => {
    const product = getProduct(line.id);
    if (!product) return summary;
    summary.quantity += line.quantity;
    summary.total += product.price * line.quantity;
    return summary;
  }, { quantity: 0, total: 0 });
}

function renderCart() {
  const summary = cartSummary();

  cartCount.textContent = summary.quantity;
  drawerCount.textContent = summary.quantity;
  mobileCartCount.textContent = summary.quantity;
  totalPrice.textContent = summary.total.toLocaleString('en-US');
  mobileCartTotal.textContent = summary.total.toLocaleString('en-US');
  mobileCart.classList.toggle('has-items', summary.quantity > 0);

  if (state.cart.length === 0) {
    cartItems.innerHTML = `
      <div class="cart-empty">
        <div>
          <span aria-hidden="true">✦</span>
          <h3>Your cart is empty</h3>
          <p>Add something from the menu and it will stay saved here on this device.</p>
        </div>
      </div>
    `;
    orderButton.disabled = true;
    orderButton.style.opacity = '.5';
    orderButton.style.cursor = 'not-allowed';
    return;
  }

  orderButton.disabled = false;
  orderButton.style.opacity = '';
  orderButton.style.cursor = '';

  cartItems.innerHTML = state.cart.map((line) => {
    const product = getProduct(line.id);
    if (!product) return '';

    return `
      <article class="cart-line">
        <div class="cart-thumb"><img src="${escapeHTML(product.image)}" alt="" loading="lazy"></div>
        <div class="cart-line-main">
          <div class="cart-line-top">
            <h4>${escapeHTML(product.name)}</h4>
            <span class="cart-line-price">EGP ${(product.price * line.quantity).toLocaleString('en-US')}</span>
          </div>
          <div class="cart-line-bottom">
            <div class="qty-control" aria-label="Quantity for ${escapeHTML(product.name)}">
              <button type="button" data-decrease="${product.id}" aria-label="Decrease quantity">−</button>
              <span>${line.quantity}</span>
              <button type="button" data-increase="${product.id}" aria-label="Increase quantity">+</button>
            </div>
            <button class="remove-line" type="button" data-remove="${product.id}">Remove</button>
          </div>
        </div>
      </article>
    `;
  }).join('');
}

function showToast(message) {
  clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add('show');
  toastTimer = setTimeout(() => toast.classList.remove('show'), 1800);
}

function addToCart(id) {
  const product = getProduct(id);
  if (!product) return;

  const existing = state.cart.find((line) => line.id === product.id);
  if (existing) existing.quantity = Math.min(99, existing.quantity + 1);
  else state.cart.push({ id: product.id, quantity: 1 });

  saveCart();
  renderCart();
  showToast(`${product.name} added to cart`);
}

function updateQuantity(id, amount) {
  const line = state.cart.find((item) => item.id === Number(id));
  if (!line) return;

  line.quantity += amount;
  if (line.quantity <= 0) {
    state.cart = state.cart.filter((item) => item.id !== Number(id));
  } else {
    line.quantity = Math.min(99, line.quantity);
  }

  saveCart();
  renderCart();
}

function removeFromCart(id) {
  const product = getProduct(id);
  state.cart = state.cart.filter((item) => item.id !== Number(id));
  saveCart();
  renderCart();
  if (product) showToast(`${product.name} removed`);
}

function openCart() {
  closeMobileNav();
  lastFocusedElement = document.activeElement;
  cartBackdrop.hidden = false;
  cartDrawer.classList.add('open');
  cartDrawer.setAttribute('aria-hidden', 'false');
  cartTrigger.setAttribute('aria-expanded', 'true');
  document.body.classList.add('drawer-open');
  requestAnimationFrame(() => cartClose.focus());
}

function closeCart() {
  cartDrawer.classList.remove('open');
  cartDrawer.setAttribute('aria-hidden', 'true');
  cartTrigger.setAttribute('aria-expanded', 'false');
  document.body.classList.remove('drawer-open');
  setTimeout(() => { cartBackdrop.hidden = true; }, 340);
  if (lastFocusedElement instanceof HTMLElement) lastFocusedElement.focus();
}

function buildWhatsAppOrder() {
  if (!state.cart.length) return;

  const summary = cartSummary();
  const lines = state.cart.map((line) => {
    const product = getProduct(line.id);
    if (!product) return '';
    return `• ${product.name} ×${line.quantity} — EGP ${product.price * line.quantity}`;
  }).filter(Boolean);

  const message = [
    '🧾 *New Order - Uncle Samir*',
    '',
    ...lines,
    '',
    `*Total Amount:* EGP ${summary.total}`,
    '',
    'Please confirm my order! 🥧'
  ].join('\n');

  const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
  window.open(url, '_blank', 'noopener,noreferrer');
}

function setCategory(category) {
  state.category = category;
  categoryChips.querySelectorAll('[data-category]').forEach((button) => {
    const active = button.dataset.category === category;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  renderMenu();
}

function resetFilters() {
  state.query = '';
  searchInput.value = '';
  setCategory('all');
  searchInput.focus();
}

function openMobileNav() {
  menuToggle.setAttribute('aria-expanded', 'true');
  menuToggle.setAttribute('aria-label', 'Close menu');
  mobileNav.classList.add('open');
  document.body.classList.add('nav-open');
}

function closeMobileNav() {
  menuToggle.setAttribute('aria-expanded', 'false');
  menuToggle.setAttribute('aria-label', 'Open menu');
  mobileNav.classList.remove('open');
  document.body.classList.remove('nav-open');
}

menuContainer.addEventListener('click', (event) => {
  const button = event.target.closest('[data-add]');
  if (button) addToCart(button.dataset.add);
});

cartItems.addEventListener('click', (event) => {
  const increase = event.target.closest('[data-increase]');
  const decrease = event.target.closest('[data-decrease]');
  const remove = event.target.closest('[data-remove]');

  if (increase) updateQuantity(increase.dataset.increase, 1);
  else if (decrease) updateQuantity(decrease.dataset.decrease, -1);
  else if (remove) removeFromCart(remove.dataset.remove);
});

searchInput.addEventListener('input', () => {
  state.query = searchInput.value;
  renderMenu();
});

categoryChips.addEventListener('click', (event) => {
  const button = event.target.closest('[data-category]');
  if (button) setCategory(button.dataset.category);
});

resetFiltersButton.addEventListener('click', resetFilters);
cartTrigger.addEventListener('click', openCart);
cartClose.addEventListener('click', closeCart);
cartBackdrop.addEventListener('click', closeCart);
orderButton.addEventListener('click', buildWhatsAppOrder);
document.querySelectorAll('[data-open-cart]').forEach((button) => button.addEventListener('click', openCart));

menuToggle.addEventListener('click', () => {
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  if (isOpen) closeMobileNav();
  else openMobileNav();
});

mobileNav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMobileNav));

window.addEventListener('scroll', () => {
  siteHeader.classList.toggle('scrolled', window.scrollY > 20);
}, { passive: true });

window.addEventListener('resize', () => {
  if (window.innerWidth > 1050) closeMobileNav();
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    if (cartDrawer.classList.contains('open')) closeCart();
    else closeMobileNav();
  }

  if (event.key === 'Tab' && cartDrawer.classList.contains('open')) {
    const focusable = cartDrawer.querySelectorAll('button:not([disabled]), a[href], input:not([disabled])');
    if (!focusable.length) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

document.getElementById('year').textContent = new Date().getFullYear();
setCategory('all');
renderCart();
siteHeader.classList.toggle('scrolled', window.scrollY > 20);
